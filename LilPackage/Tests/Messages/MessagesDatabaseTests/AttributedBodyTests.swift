import Foundation
import MessagesDatabase
import Testing

struct AttributedBodyTests {
  @Test
  func decodesPlainString() {
    #expect(AttributedBody.text(from: Data(hello)) == "Hello")
  }

  @Test
  func decodesMultibyteUTF8AndAttachmentPlaceholders() {
    #expect(AttributedBody.text(from: Data(emoji)) == "See you 🎉\u{FFFC}")
  }

  @Test
  func decodesMutableStringWithAttributes() {
    #expect(AttributedBody.text(from: Data(mutableWithAttributes)) == "Lunch at noon?")
  }

  @Test
  func decodesTwoByteLength() {
    let text = String(repeating: "a", count: 300)
    let data = splice(text, lengthBytes: [0x81, 0x2C, 0x01])
    #expect(AttributedBody.text(from: data) == text)
  }

  @Test
  func decodesFourByteLength() {
    let text = String(repeating: "b", count: 70_000)
    let data = splice(text, lengthBytes: [0x82, 0x70, 0x11, 0x01, 0x00])
    #expect(AttributedBody.text(from: data) == text)
  }

  @Test
  func returnsNilForTruncatedData() {
    #expect(AttributedBody.text(from: Data(hello.prefix(76))) == nil)
  }

  @Test
  func returnsNilForInvalidUTF8() {
    var bytes = hello
    bytes[75] = 0xFF
    #expect(AttributedBody.text(from: Data(bytes)) == nil)
  }

  @Test
  func returnsNilForUnrelatedData() {
    #expect(AttributedBody.text(from: Data()) == nil)
    #expect(AttributedBody.text(from: Data("not a typedstream".utf8)) == nil)
  }
}

/// Builds a blob whose string payload has the given length encoding, reusing the `hello` archive
/// around it.
private func splice(_ text: String, lengthBytes: [UInt8]) -> Data {
  let prefix = hello.prefix(through: 72)
  let suffix = hello.suffix(from: 79)
  return Data(prefix + lengthBytes + Array(text.utf8) + suffix)
}

